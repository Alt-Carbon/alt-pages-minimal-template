function fromGit() {
  try {
    const url = execSync("git remote get-url origin", { stdio: ["ignore", "pipe", "ignore"] }).toString().trim();
    const m = /github\.com[:/]([^/]+)\/([^/.\s]+)(?:\.git)?$/i.exec(url);
    return m ? `${m[1]}/${m[2]}` : "";
  } catch {
    return "";
  }
}
